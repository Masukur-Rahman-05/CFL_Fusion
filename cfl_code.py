# ── Helper ────────────────────────────────────────────────────
def mcnemar_test(y_true, y_pred_a, y_pred_b,
                 name_a='Model A', name_b='Model B'):
    """
    McNemar's test comparing classifier A vs classifier B.

    Contingency table (off-diagonal cells only matter):
        b = A correct, B wrong
        c = A wrong,   B correct

    H0: both models make the same errors (b == c)
    H1: error distributions differ

    Uses continuity correction (correction=True) which is
    recommended when b+c < 25. Safe for all sample sizes.

    Returns dict with table, statistic, p-value, and interpretation.
    """
    correct_a = (y_pred_a == y_true)
    correct_b = (y_pred_b == y_true)

    # Off-diagonal counts
    b = int(np.sum( correct_a & ~correct_b))   # A right, B wrong
    c = int(np.sum(~correct_a &  correct_b))   # A wrong,  B right

    # Diagonal counts (not used by McNemar but shown for transparency)
    a = int(np.sum( correct_a &  correct_b))   # both right
    d = int(np.sum(~correct_a & ~correct_b))   # both wrong

    table = [[a, b], [c, d]]

    # Run test — exact=False uses chi-squared approximation with
    # continuity correction, which is appropriate for large n
    result = mcnemar(table, exact=False, correction=True)

    direction = f"{name_a} better" if b > c else \
                f"{name_b} better" if c > b else "tie"
    significant = result.pvalue < 0.05

    return {
        'name_a':      name_a,
        'name_b':      name_b,
        'a_both_correct': a,
        'b_a_right_b_wrong': b,
        'c_a_wrong_b_right': c,
        'd_both_wrong': d,
        'statistic':   result.statistic,
        'p_value':     result.pvalue,
        'significant': significant,
        'direction':   direction,
    }

